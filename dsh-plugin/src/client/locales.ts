export type Translate = (key: BeadAtlasLocaleKey, params?: Record<string, string | number>) => string

/** Minimal translator used outside DSH (tests) with the same `{name}` interpolation. */
export function createTranslator(table: Record<BeadAtlasLocaleKey, string>): Translate {
  return (key, params) => {
    const template = table[key] ?? key
    if (params === undefined) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
  }
}
